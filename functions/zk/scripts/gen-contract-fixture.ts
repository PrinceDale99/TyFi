// Generates contracts/typhoon_resilience_vault/src/zk_fixture.rs: a real
// Groth16 proof + verifying key so the vault's tests run the actual BN254
// pairing check. Re-run after any trusted-setup change:
//   npx ts-node --transpile-only zk/scripts/gen-contract-fixture.ts
import fs from 'fs';
import path from 'path';
import { encodeVerifyingKey, symbolToField } from '../encoding';
import { loadOracleZkKey, proveWeatherReading, shutdownProver } from '../prover';

const OUT = path.join(__dirname, '..', '..', '..', 'contracts', 'typhoon_resilience_vault', 'src', 'zk_fixture.rs');
const TEST_KEY = '01'.repeat(32);
const reading = { typhoonId: 'ZK_STORM', region: 'Visayas', windSpeed: 172, windFloor: 150, damagePercentage: 85 };

const bytes = (b: Buffer) => `[${[...b].map((x) => `0x${x.toString(16).padStart(2, '0')}`).join(', ')}]`;
const field = (v: bigint) => bytes(Buffer.from(v.toString(16).padStart(64, '0'), 'hex'));

async function main() {
  const vkJson = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'artifacts', 'verification_key.json'), 'utf8'));
  const vk = encodeVerifyingKey(vkJson);
  const key = await loadOracleZkKey(TEST_KEY);
  const { proof } = await proveWeatherReading(reading, key);

  const src = `// @generated by functions/zk/scripts/gen-contract-fixture.ts — do not edit.
// Real Groth16 proof for: typhoon=${reading.typhoonId}, region=${reading.region},
// wind_floor=${reading.windFloor}, damage=${reading.damagePercentage} (private wind_speed=${reading.windSpeed}).

pub const TYPHOON: &str = "${reading.typhoonId}";
pub const REGION: &str = "${reading.region}";
pub const WIND_FLOOR: u32 = ${reading.windFloor};
pub const DAMAGE: u32 = ${reading.damagePercentage};

pub const ORACLE_KEY_HASH: [u8; 32] = ${field(key.keyHash)};
/// symbol_to_field(TYPHOON) / symbol_to_field(REGION) as computed off-chain.
pub const TYPHOON_FIELD: [u8; 32] = ${field(symbolToField(reading.typhoonId))};
pub const REGION_FIELD: [u8; 32] = ${field(symbolToField(reading.region))};

pub const VK_ALPHA: [u8; 64] = ${bytes(vk.alpha)};
pub const VK_BETA: [u8; 128] = ${bytes(vk.beta)};
pub const VK_GAMMA: [u8; 128] = ${bytes(vk.gamma)};
pub const VK_DELTA: [u8; 128] = ${bytes(vk.delta)};
pub const VK_IC: [[u8; 64]; ${vk.ic.length}] = [
${vk.ic.map((p) => `    ${bytes(p)},`).join('\n')}
];

pub const PROOF_A: [u8; 64] = ${bytes(proof.a)};
pub const PROOF_B: [u8; 128] = ${bytes(proof.b)};
pub const PROOF_C: [u8; 64] = ${bytes(proof.c)};
`;
  fs.writeFileSync(OUT, src);
  console.log(`wrote ${OUT}`);
  await shutdownProver();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
